_ICON_CACHE: Dict[str, QIcon] = {}


def get_default_color() -> str:
    """Returns the primary brand color matching current active theme."""
    return "#0284c7" if get_current_theme() == "light" else "#38bdf8"


def get_icon(name: str, color: Optional[str] = None, size: int = 20) -> QIcon:
    """
    Renders a crisp vector QIcon from SVG definitions.
    Adapts automatically to light/dark themes if color is omitted.
    """
    path_data = SVG_PATHS.get(name)
    if not path_data:
        return QIcon()

    actual_color = color if color is not None else get_default_color()
    cache_key = f"{name}_{actual_color}_{size}"

    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    svg_content = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{actual_color}">{path_data}</svg>'
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter)
    painter.end()

    icon = QIcon(pixmap)
    _ICON_CACHE[cache_key] = icon
    return icon
